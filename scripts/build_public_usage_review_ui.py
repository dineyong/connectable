    '미러링 전환으로 임시 정상, 재연결 뒤 재발', 'U28E590D의 초기 출력 문제와 제품 소개',
    '4K 선택 가능 여부와 60/30Hz 설정', 'MH510의 DP 영상과 동시 충전 보고',
