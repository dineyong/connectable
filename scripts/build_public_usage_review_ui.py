def safe_external_url(value):
    parsed = urlsplit(value)
    host = parsed.hostname or ''
    return (parsed.scheme == 'https' and not parsed.username and not parsed.password
            and '.' in host and any(c.isalpha() for c in host)
            and host != 'localhost' and not host.endswith(('.local', '.internal')))


def build(mapping_path=review.MAPPING, source_path=review.SOURCE):
    errors = review.validate_files(mapping_path, source_path)
    if errors:
        raise ValueError('Review mapping validation failed; no asset generated')
    records = []
    for _, r, _ in review.read_jsonl(mapping_path):
        m = r['mapping']
        if not safe_external_url(m['source']['source_url']):
            raise ValueError('Only public HTTPS source links may enter the UI')
        item = dict(id=r['source_id'], title=TITLES[int(r['id'].split('-')[1])-1],
                    source=copy.deepcopy(m['source']), grade='C', reviewStatus='NEEDS_REVIEW',
                    publicStatus='UNKNOWN', basis='USER_REPORT',
                    environment=copy.deepcopy(m['environment']),
                    nodes=copy.deepcopy(m['nodes']), ports=copy.deepcopy(m['ports']),
                    configurations=copy.deepcopy(m['configurations']), goal=copy.deepcopy(m['goal']),
                    attempts=copy.deepcopy(m['attempts']), observations=copy.deepcopy(m['observations']),
                    functionalObservations=copy.deepcopy(r['functional_observations']),
                    evidence=copy.deepcopy(m['evidence']),
                    evidenceRoles=[{k:v for k,v in a.items() if k!='source_pointers'}
                                   for a in copy.deepcopy(r['evidence_annotations'])],
                    unscopedStatements=copy.deepcopy(r['unscoped_statements']),
                    missing=copy.deepcopy(m['review']['missing_fields']),
                    commercial=copy.deepcopy(m['review']['commercial_context']))
        if 'semantic_review' in r:
            item['semanticReview'] = copy.deepcopy(r['semantic_review'])
        records.append(item)
    records.sort(key=lambda r:r['id'])
    data = dict(version='review-ui-1', recordStatus='REVIEW_ONLY', publicStatus='UNKNOWN',
                approvedGold=0, records=records)
    payload = json.dumps(data, ensure_ascii=False, separators=(',',':'))
    payload = payload.replace('<', '\\u003c').replace('\u2028','\\u2028').replace('\u2029','\\u2029')
    return '// Generated by scripts/build_public_usage_review_ui.py; do not edit.\nwindow.CONNECTABLE_REVIEW_DATA = '+payload+';\n'


if __name__=='__main__':
    OUTPUT.write_text(build(),encoding='utf-8')
    print('Generated web/review-data.js: 18 review-only cases, no approval')
